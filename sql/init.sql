-- Central Log table --
CREATE TABLE IF NOT EXISTS clogs (
  id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  -- node_id INT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
