-- Create the tables with ownership assigned to "vns"

-- Node IPs --
CREATE TABLE IF NOT EXISTS nodes (
  id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  ip VARCHAR(15) NOT NULL, -- TODO: might be UNIQUE (?), not sure yet.
  port INT NOT NULL,
  max_seq BIGINT NOT NULL DEFAULT 0 -- max log sequence number from log_seq
);

\copy nodes FROM 'sql/nodes.csv' DELIMITER ',' CSV HEADER; -- using relative path

SELECT * FROM nodes;

-- Routing Table --
CREATE TABLE IF NOT EXISTS routes (
  id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  src INT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  dst INT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  next INT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  cost INT DEFAULT 0
);

\copy routes FROM 'sql/routes.csv' DELIMITER ',' CSV HEADER; -- using relative path

SELECT * FROM routes LIMIT 10;

CREATE TABLE IF NOT EXISTS routes_mkt (
  id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  root TEXT NOT NULL
);

-- Flow --
CREATE TABLE IF NOT EXISTS flows (
  id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  src INT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  dst INT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  is_done BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS metadata (
  key VARCHAR(30) PRIMARY KEY,
  value BIGINT NOT NULL DEFAULT 0
);

